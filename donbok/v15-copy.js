function rewriteMachineLanguage(root=document){
 root.querySelectorAll('*').forEach(el=>{
   if(el.children.length)return;
   let t=el.textContent;
   if(!t)return;
   t=t.replace(/근거 겹침:\s*(매우 강함|강함)/g,'이 시기가 유독 선명합니다');
   t=t.replace(/약한 신호를 결제 유도로 과장하지 않겠습니다\.?/g,'');
   t=t.replace(/근거가 충분하지 않습니다\.?/g,'');
   t=t.replace(/특정 사건 하나가 다른 신호를 압도하지 않습니다\.?/g,'');
   if(t!==el.textContent)el.textContent=t.trim();
 });
}

