function currentTopic(){return $('.hwTopic.on')?.textContent?.trim()||''}

function rewritePast(){
 $$('#readingMount > .hwPaper').forEach(card=>{
  const ey=card.querySelector('.hwEy');if(!ey)return;
  if(ey.textContent.includes('첫 풀이 원칙')){card.remove();return}
  if(!ey.textContent.includes('년 · 지나온 흐름')||card.dataset.v15Done)return;
  const year=(ey.textContent.match(/\d{4}/)||[])[0]||'';
  const h=card.querySelector('h2');if(!h)return;
  const label=h.textContent.trim();if(!TITLES[label])return;
  card.dataset.v15Done='1';
  setText(h,`${year}년, ${TITLES[label]}`);
  setText(card.querySelector('p'),bodyFor(label));
  card.querySelector('.hwConf')?.remove();
  const details=card.querySelector('.hwWhy');if(details){setText(details.querySelector('summary'),'이 시기를 조금 더 풀어보면');setText(details.querySelector('p'),reasonFor(label))}
 });
}

function rewriteFuture(){
 const card=$$('#readingMount > .hwPaper').find(c=>c.querySelector('.hwEy')?.textContent.includes('앞으로 먼저 볼 것'));if(!card)return;
 const lone=card.querySelector(':scope > h2');
 if(lone&&/억지로|한 사건/.test(lone.textContent)){setText(lone,'앞으로는 크게 뒤집기보다, 다음 판을 준비하는 흐름이 먼저입니다.');setText(card.querySelector(':scope > p'),'당장 모든 것이 한꺼번에 바뀌기보다, 지금 가진 것 가운데 무엇을 남기고 무엇을 정리할지 차례를 잡는 흐름에 가깝습니다. 큰 결정보다 미리 준비해둔 선택지가 나중의 차이를 만듭니다.');return}
 card.querySelectorAll(':scope > div').forEach(div=>{
   if(div.dataset.v15Done)return;const h=div.querySelector('h2');if(!h)return;
   const m=h.textContent.match(/(\d{4})년 · (.+)/);if(!m)return;const [,year,label]=m;if(!TITLES[label.trim()])return;
   div.dataset.v15Done='1';setText(h,`${year}년, ${TITLES[label.trim()]}`);setText(div.querySelector('p'),bodyFor(label.trim()));div.querySelector('.hwConf')?.remove();
 });
}

function rewriteTopic(){
 const box=$('#topicPreview');if(!box)return;const h=box.querySelector('h3'),p=box.querySelector('p');if(!h||!p)return;
 if(!box.dataset.v15Fallback&&(/근거가 충분하지|강하게 단정/.test(h.textContent+p.textContent))){const f=TOPIC_FALLBACK[currentTopic()];if(f){box.dataset.v15Fallback='1';setText(h,f[0]);setText(p,f[1])}}
 const m=h.textContent.match(/(\d{4})년, (.+) 쪽이 가장 먼저 잡힙니다/);if(m&&!box.dataset.v15Event){const [,year,label]=m;if(TITLES[label.trim()]){box.dataset.v15Event='1';setText(h,`${year}년, ${TITLES[label.trim()]}`);setText(p,bodyFor(label.trim()))}}
 box.querySelectorAll('.hwConf').forEach(x=>x.remove());
 const pay=box.querySelector('.hwPaywall');if(pay&&!pay.dataset.v15Done){pay.dataset.v15Done='1';setText(pay.querySelector('h3'),'가장 중요한 시기와 그다음 선택까지 이어서 봅니다.');setText(pay.querySelector('button'),'이 풀이 끝까지 보기 →')}
}

function rewriteStatic(){
 setText($('#result .resultHero .ey'),'현월당 첫 풀이');
 setHTML($('#result .resultHero h1'),'먼저, 지나온 흐름부터<br>짚어보겠습니다.');
 const rp=$('#replayNote');if(rp&&!rp.dataset.v15){rp.dataset.v15='1';setText(rp,'지금의 선택은 지나온 흐름과 이어져 있습니다. 먼저 삶이 크게 움직였던 때를 봅니다.')}
 const seal=$('#sealMount .hwSeal span');if(seal)setText(seal,'같은 명식의 첫 풀이는 다시 보더라도 내용이 달라지지 않습니다.');
 setText($('#checkout .engine'),'테스트 화면 · 실제 결제는 진행되지 않습니다.');
}

function cleanMachineWords(){
 $$('body *').forEach(el=>{if(el.children.length)return;const before=el.textContent||'';let after=before.replace(/근거 겹침:\s*(매우 강함|강함)/g,'').replace(/약한 신호를 결제 유도로 과장하지 않겠습니다\.?/g,'').replace(/근거가 충분하지 않습니다\.?/g,'').replace(/특정 사건 하나가 다른 신호를 압도하지 않습니다\.?/g,'');if(after!==before)setText(el,after.trim())});
}

let scheduled=false;
function apply(){scheduled=false;rewriteStatic();rewritePast();rewriteFuture();rewriteTopic();cleanMachineWords()}
function schedule(){if(scheduled)return;scheduled=true;requestAnimationFrame(apply)}
const observer=new MutationObserver(schedule);observer.observe(document.body,{childList:true,subtree:true});
apply();
